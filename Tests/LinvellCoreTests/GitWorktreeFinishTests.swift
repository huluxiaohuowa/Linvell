import Foundation
import XCTest
@testable import LinvellCore

final class GitWorktreeFinishTests: XCTestCase {
    func testFinishKeepsDirtyWorktreeThenFastForwardsAndKeepsBranch() throws {
        let fixture = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let root = fixture.appendingPathComponent("repo")
        try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
        defer { try? FileManager.default.removeItem(at:fixture) }
        let repo = GitRepository(root:root)
        _ = try repo.run(["init","-b","main"])
        _ = try repo.run(["config","user.name","Fixture"])
        _ = try repo.run(["config","user.email","fixture@example.invalid"])
        _ = try repo.run(["config","commit.gpgsign","false"])
        _ = try repo.run(["commit","--allow-empty","-m","Initial"])
        let worktree = fixture.appendingPathComponent("linked worktree")
        _ = try repo.run(["worktree","add","-b","review/feature","--",worktree.path])
        let entry = try XCTUnwrap(repo.worktrees().first { $0.branch == "review/feature" })
        let file = worktree.appendingPathComponent("change.txt")
        try "worktree change\n".write(to:file,atomically:true,encoding:.utf8)
        let originalHead = try repo.run(["rev-parse","HEAD"])
        XCTAssertThrowsError(try repo.finishWorktree(entry,into:"main"))
        XCTAssertEqual(try repo.run(["rev-parse","HEAD"]),originalHead)
        XCTAssertTrue(FileManager.default.fileExists(atPath:file.path))
        let child = GitRepository(root:worktree)
        try child.stage(try XCTUnwrap(child.changes().first))
        try child.commit("Worktree change")
        let expected = try child.run(["rev-parse","HEAD"])
        try repo.finishWorktree(entry,into:"main")
        XCTAssertEqual(try repo.run(["rev-parse","HEAD"]),expected)
        XCTAssertEqual(try repo.run(["rev-parse","refs/heads/review/feature"]),expected)
        XCTAssertEqual(try repo.worktrees().count,1)
    }
    func testSelectedTargetConflictCanAbortAndResumeThenFinish() throws {
        let fixture = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let root = fixture.appendingPathComponent("repo")
        try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
        defer { try? FileManager.default.removeItem(at:fixture) }
        let repo = GitRepository(root:root)
        _ = try repo.run(["init","-b","main"])
        _ = try repo.run(["config","user.name","Fixture"])
        _ = try repo.run(["config","user.email","fixture@example.invalid"])
        _ = try repo.run(["config","commit.gpgsign","false"])
        func write(_ text: String,in repo: GitRepository) throws {
            try text.write(to:repo.root.appendingPathComponent("shared.txt"),atomically:true,encoding:.utf8)
            _ = try repo.run(["add","--","shared.txt"])
            try repo.commit(text)
        }
        try write("base\n",in:repo)
        let main = try repo.run(["rev-parse","HEAD"])
        let sourcePath = fixture.appendingPathComponent("source")
        _ = try repo.run(["worktree","add","-b","feature","--",sourcePath.path])
        let source = GitRepository(root:sourcePath)
        try write("incoming\n",in:source)
        let sourceHead = try source.run(["rev-parse","HEAD"])
        let targetPath = fixture.appendingPathComponent("target")
        _ = try repo.run(["worktree","add","-b","integration","--",targetPath.path])
        let target = GitRepository(root:targetPath)
        try write("current\n",in:target)
        let targetHead = try target.run(["rev-parse","HEAD"])
        let entry = try XCTUnwrap(repo.worktrees().first { $0.branch == "feature" })
        let pending = try XCTUnwrap(repo.finishWorktree(entry,into:"integration"))
        XCTAssertEqual(try pending.conflicts().map(\.path),["shared.txt"])
        XCTAssertThrowsError(try pending.complete())
        XCTAssertThrowsError(try pending.markResolved("shared.txt"))
        let versions = try pending.versions("shared.txt")
        XCTAssertEqual(versions.current,"current\n")
        XCTAssertEqual(versions.incoming,"incoming\n")
        try pending.abort()
        XCTAssertEqual(try target.run(["rev-parse","HEAD"]),targetHead)
        XCTAssertTrue(try target.changes().isEmpty)
        XCTAssertTrue(FileManager.default.fileExists(atPath:sourcePath.path))
        _ = try XCTUnwrap(repo.finishWorktree(entry,into:"integration"))
        let resumed = try XCTUnwrap(repo.finishWorktree(entry,into:"integration"))
        try resumed.resolve("shared.txt",useIncoming:true)
        XCTAssertTrue(try resumed.conflicts().isEmpty)
        try resumed.complete()
        XCTAssertEqual(try String(contentsOf:targetPath.appendingPathComponent("shared.txt"),encoding:.utf8),"incoming\n")
        XCTAssertEqual(try repo.run(["rev-parse","HEAD"]),main)
        XCTAssertEqual(try repo.run(["rev-parse","refs/heads/feature"]),sourceHead)
        XCTAssertFalse(FileManager.default.fileExists(atPath:sourcePath.path))
        XCTAssertEqual(try target.run(["rev-list","--parents","-1","HEAD"]).split(whereSeparator:\.isWhitespace).count,3)
    }
    func testMergedCleanupRechecksHeadAndKeepsIgnoredFiles() throws {
        let fixture = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let root = fixture.appendingPathComponent("repo")
        try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
        defer { try? FileManager.default.removeItem(at:fixture) }
        let repo = GitRepository(root:root)
        _ = try repo.run(["init","-b","main"])
        _ = try repo.run(["config","user.name","Fixture"])
        _ = try repo.run(["config","user.email","fixture@example.invalid"])
        _ = try repo.run(["config","commit.gpgsign","false"])
        try "local.cache\n".write(to:root.appendingPathComponent(".gitignore"),atomically:true,encoding:.utf8)
        _ = try repo.run(["add",".gitignore"]); try repo.commit("Initial")
        let cleanPath = fixture.appendingPathComponent("clean")
        let ignoredPath = fixture.appendingPathComponent("ignored")
        _ = try repo.run(["worktree","add","-b","clean","--",cleanPath.path])
        _ = try repo.run(["worktree","add","-b","ignored","--",ignoredPath.path])
        try "fixture\n".write(to:ignoredPath.appendingPathComponent("local.cache"),atomically:true,encoding:.utf8)
        let candidates = try repo.mergedWorktrees(into:"main")
        XCTAssertEqual(candidates.map(\.branch),["clean"])
        let entry = try XCTUnwrap(candidates.first)
        XCTAssertThrowsError(try repo.removeMergedWorktree(entry,into:"main",expectedHead:"invalid"))
        try repo.removeMergedWorktree(entry,into:"main",expectedHead:repo.worktreeHead(entry))
        XCTAssertFalse(FileManager.default.fileExists(atPath:cleanPath.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath:ignoredPath.appendingPathComponent("local.cache").path))
    }
    func testSquashCleanupKeepsBranchAndDetectsNewIgnoredFiles() throws {
        let fixture = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let root = fixture.appendingPathComponent("repo")
        try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
        defer { try? FileManager.default.removeItem(at:fixture) }
        let repo = GitRepository(root:root)
        _ = try repo.run(["init","-b","main"])
        _ = try repo.run(["config","user.name","Fixture"])
        _ = try repo.run(["config","user.email","fixture@example.invalid"])
        _ = try repo.run(["config","commit.gpgsign","false"])
        try "*.cache\n".write(to:root.appendingPathComponent(".gitignore"),atomically:true,encoding:.utf8)
        _ = try repo.run(["add",".gitignore"]); try repo.commit("Initial")
        let sourcePath = fixture.appendingPathComponent("source")
        _ = try repo.run(["worktree","add","-b","feature","--",sourcePath.path])
        let source = GitRepository(root:sourcePath)
        try "change\n".write(to:sourcePath.appendingPathComponent("feature.txt"),atomically:true,encoding:.utf8)
        _ = try source.run(["add","feature.txt"]); try source.commit("Feature")
        _ = try repo.run(["merge","--squash","feature"]); try repo.commit("Squashed feature")
        let candidate = try XCTUnwrap(repo.cleanupCandidates(into:"main").first)
        XCTAssertFalse(candidate.ancestor)
        let newFile = sourcePath.appendingPathComponent("new.cache")
        try "ignored\n".write(to:newFile,atomically:true,encoding:.utf8)
        XCTAssertThrowsError(try repo.removeCleanupCandidate(candidate,into:"main",deleteBranch:true))
        XCTAssertTrue(FileManager.default.fileExists(atPath:newFile.path))
        let confirmed = try XCTUnwrap(repo.cleanupCandidates(into:"main").first)
        XCTAssertEqual(confirmed.ignored,["new.cache"])
        try repo.removeCleanupCandidate(confirmed,into:"main",deleteBranch:true)
        XCTAssertFalse(FileManager.default.fileExists(atPath:sourcePath.path))
        XCTAssertFalse(try repo.run(["rev-parse","--verify","refs/heads/feature"]).isEmpty)
    }
}
